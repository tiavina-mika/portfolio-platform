/**
 * Copies a text to the clipboard. The asynchronous clipboard needs a secure page; elsewhere the text is
 * put in a hidden field and copied from it. Resolves to whether the copy worked.
 */
export const copyToClipboard = async (text: string): Promise<boolean> => {
  if (navigator.clipboard && window.isSecureContext) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch { /* refused (permission, focus): the fallback below is tried */ }
  }

  const field = document.createElement('textarea');

  field.value = text;
  field.setAttribute('readonly', '');
  field.style.position = 'fixed';
  field.style.opacity = '0';
  document.body.appendChild(field);
  field.select();

  try {
    return document.execCommand('copy');
  } catch {
    return false;
  } finally {
    field.remove();
  }
};
